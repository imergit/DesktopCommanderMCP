#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
process.env.IMERMCP_ENABLE_IMERTERM='1';
process.env.IMERMCP_IMERTERM_HOST_EXE=process.env.IMERMCP_TEST_IMERTERM_HOST_EXE;
process.env.IMERMCP_IMERTERM_LOCAL_ROOT=process.env.IMERMCP_TEST_IMERTERM_LOCAL_ROOT;
const { handleImerTermTool } = await import('../dist/imermcp-local/imerterm-tools.js');
const body = r => r.structuredContent ?? JSON.parse(r.content.map(x=>x.text??'').join('\n'));
const invoke = async (name,args={}) => await handleImerTermTool(name,args);
const call = async (name,args={}) => body(await invoke(name,args));
const project='imermcp-c2-e2e', target='p53-c2-e2e';
const work=path.join(process.env.IMERMCP_TEST_IMERTERM_LOCAL_ROOT,'work');
const base = (task_id,script,extra={}) => ({task_id,created_at_utc:new Date().toISOString(),project_id:project,target_id:target,mutation_class:'NONE',capability:'POWERSHELL_EXEC',working_directory:work,script,timeout_ms:15000,graceful_stop_ms:1000,max_raw_output_bytes:65536,execution_mode:'ASYNC',admission_timeout_ms:2000,...extra});
const wait = async id => await call('imerterm_task_wait',{task_id:id,poll_seconds:1,wait_timeout_seconds:15});
const show = async id => await call('imerterm_task_show',{task_id:id});
let checks=0;
const pass = label => { checks++; console.log('PASS '+label); };
const counter=path.join(work,'c2-single-effect.txt');
await fs.rm(counter,{force:true});const id1=randomUUID();
const script1=`$p='${counter.replaceAll('\\','\\\\')}'; if(Test-Path -LiteralPath $p){$n=[int](Get-Content -LiteralPath $p)}else{$n=0}; Set-Content -LiteralPath $p -Value ($n+1); Start-Sleep -Milliseconds 800; exit 0`;
const req1=base(id1,script1);
const admitted1=await call('imerterm_run_powershell',req1);
assert.equal(admitted1.status,'ADMITTED');
await wait(id1);
const exact1=await call('imerterm_run_powershell',req1);
assert.equal(exact1.task_id,id1);
assert.equal((await fs.readFile(counter,'utf8')).trim(),'1');
pass('exact retry does not cause second effect');
const terminalAgain=await show(id1);
assert.equal(terminalAgain.task.terminal,true);
assert.equal(terminalAgain.task.state,'SUCCEEDED');
pass('terminal task is durably re-observable');
const cancelTerminal=await call('imerterm_task_cancel',{task_id:id1});
assert.equal(cancelTerminal.task.task_id,id1);
assert.equal(cancelTerminal.task.terminal,true);
pass('cancel after terminal is idempotent observation');const ids=[];
for(let i=0;i<4;i++){ const id=randomUUID(); ids.push(id); await call('imerterm_run_powershell',base(id,`Start-Sleep -Milliseconds ${100+i*20}; exit 0`)); await wait(id); }
const page1=await call('imerterm_task_list',{project_id:project,limit:2});
assert.equal(page1.task_list.items.length,2); assert.ok(page1.task_list.next_cursor);
const page2=await call('imerterm_task_list',{project_id:project,limit:2,cursor:page1.task_list.next_cursor});
assert.ok(page2.task_list.items.every(x=>x.project_id===project));
assert.equal(new Set([...page1.task_list.items,...page2.task_list.items].map(x=>x.task_id)).size,4);
pass('bounded pagination and project isolation');
const badList=await invoke('imerterm_task_list',{project_id:project,limit:101});
assert.equal(badList.isError,true); pass('list upper bound fails closed');
const badId=await invoke('imerterm_task_show',{task_id:'not-a-uuid'});
assert.equal(badId.isError,true); pass('malformed task id fails closed');
const idBusy1=randomUUID(), idBusy2=randomUUID();
const a1=await call('imerterm_run_powershell',base(idBusy1,"Start-Sleep -Seconds 3; exit 0"));
assert.equal(a1.status,'ADMITTED');
const a2=await call('imerterm_run_powershell',base(idBusy2,"Start-Sleep -Seconds 3; exit 0"));
assert.equal(a2.status,'BUSY'); pass('bounded BUSY backpressure');
await wait(idBusy1);
console.log(`CHECKS=${checks} FAILURES=0`);
console.log('IMERMCP_VNEXT_C2_ADVERSARIAL_PASS');